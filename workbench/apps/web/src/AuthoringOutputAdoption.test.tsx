it("合法精确采用回执通过；另一个成员、快照、输出、包或自动后续声明被拒绝", async () => {
  const request = pending();
  const value = await ack(request);
  await expect(
    validateAdoption(value, request, build, value.package_etag),
  ).resolves.toEqual(value);
  for (const mutate of [
    (v: AuthoringOutputAdopted) => {
      v.actor_id = uid(99);
    },
    (v: AuthoringOutputAdopted) => {
      v.output.build_identity.draft_revision++;
    },
    (v: AuthoringOutputAdopted) => {
      v.output.document_version_id = uid(99);
    },
    (v: AuthoringOutputAdopted) => {
      v.package.manifest.members[0].file_digest = "f".repeat(64);
    },
    (v: AuthoringOutputAdopted) => {
      Object.assign(v, { automatically_started_review: true });
    },
  ]) {
    const changed = structuredClone(value);
    mutate(changed);
    await expect(
      validateAdoption(changed, request, build, value.package_etag),
    ).rejects.toThrow("原请求保留");
  }
});

it("追加必须保留已读取包的所有原成员，替换旧成员并重算摘要也不能蒙混回执", async () => {
  const old = (await ack()).package;
  old.manifest.members[0].document_version_id = uid(30);
  old.digest = await jsonDigest(old.manifest);
  const etag = `"bid-package-head:${old.manifest.package_id}:${old.digest}"`;
  const request = pending();
  request.base = await checkedAdoptionBase(
    old,
    scope.bidId,
    old.manifest.package_id,
    etag,
  );
  request.body.package_id = old.manifest.package_id;
  const value = await ack(request);
  value.package.manifest.revision = 2;
  value.package.manifest.predecessor_digest = old.digest;
  value.package.manifest.members.unshift(
    structuredClone(old.manifest.members[0]),
  );
  value.package.digest = await jsonDigest(value.package.manifest);
  value.package_etag = `"bid-package-head:${old.manifest.package_id}:${value.package.digest}"`;
  await expect(
    validateAdoption(value, request, build, value.package_etag),
  ).resolves.toEqual(value);
  value.package.manifest.members[0].purposes = ["替换旧成员"];
  value.package.digest = await jsonDigest(value.package.manifest);
  value.package_etag = `"bid-package-head:${old.manifest.package_id}:${value.package.digest}"`;
  await expect(
    validateAdoption(value, request, build, value.package_etag),
  ).rejects.toThrow("原请求保留");
});

it("首次请求失响应后刷新，结束项目仍只按原 key 与原包条件恢复", async () => {
  let success = false;
  const writes = install(async (options) => {
    if (!success) throw new TypeError("lost response");
    const request = JSON.parse(
      sessionStorage.getItem(adoptionStorageKey(scope))!,
    ) as PendingAdoption;
    expect(JSON.parse(String(options.body))).toEqual(request.body);
    const value = await ack(request);
    return json(value, value.package_etag, 201);
  });
  const first = show();
  await userEvent.click(
    screen.getByRole("button", { name: "选择投标包并采用此文件" }),
  );
  await userEvent.type(
    screen.getByLabelText("生成文件采用原因"),
    "采用本次确认稿",
  );
  await userEvent.click(
    screen.getByRole("button", { name: "采用文件并新建投标包" }),
  );
  await screen.findByText("暂时无法连接服务。已完成的资料仍保留，请稍后重试。");
  first.unmount();
  success = true;
  show(true);
  await userEvent.click(
    screen.getByRole("button", { name: "恢复原文件采用请求" }),
  );
  await screen.findByText(/生成文件已采用到投标包/);
  expect(writes).toHaveLength(2);
  expect(writes[1].body).toEqual(writes[0].body);
  expect(new Headers(writes[1].headers).get("Idempotency-Key")).toEqual(
    new Headers(writes[0].headers).get("Idempotency-Key"),
  );
  expect(sessionStorage.getItem(adoptionStorageKey(scope))).toBeNull();
});

it.each(["conflict", "foreign_ack"])(
  "%s 结果保留原记录，不会替换 key 或宣告成功",
  async (mode) => {
    const request = pending();
    sessionStorage.setItem(adoptionStorageKey(scope), JSON.stringify(request));
    const writes = install(async () => {
      if (mode === "conflict")
        return json(
          { code: "IDEMPOTENCY_CONFLICT", message: "需核对原命令" },
          undefined,
          409,
        );
      const value = await ack(request);
      value.actor_id = uid(99);
      return json(value, value.package_etag, 201);
    });
    show();
    await userEvent.click(
      screen.getByRole("button", { name: "恢复原文件采用请求" }),
    );
    await screen.findByText(
      mode === "conflict" ? "需核对原命令" : /采用回执与原文件/,
    );
    expect(
      JSON.parse(sessionStorage.getItem(adoptionStorageKey(scope))!),
    ).toEqual(request);
    expect(
      screen.queryByText(/生成文件已采用到投标包/),
    ).not.toBeInTheDocument();
    expect(writes).toHaveLength(1);
  },
);

